const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const net = require("node:net");
const { spawn } = require("node:child_process");
const { once } = require("node:events");
const { TOTP, Secret } = require("otpauth");
const { resolvePuppeteer, resolveChromePath } = require("./smoke-utils.cjs");
const puppeteer = resolvePuppeteer();

const root = path.resolve(__dirname, "..");
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "multi-session-smoke-"));
  const authDir = path.join(dir, "cli-auth");
  const projectDir = path.join(dir, "projects");
  const subA = path.join(projectDir, "sub-a");
  const subB = path.join(projectDir, "sub-b");
  fs.mkdirSync(authDir, { recursive: true });
  fs.mkdirSync(subA, { recursive: true });
  fs.mkdirSync(subB, { recursive: true });

  const reservation = net.createServer();
  reservation.listen(0, "127.0.0.1");
  await once(reservation, "listening");
  const port = reservation.address().port;
  await new Promise((resolve) => reservation.close(resolve));

  const base = `http://127.0.0.1:${port}`;

  const child = spawn(process.execPath, ["server/dist/index.js"], {
    cwd: root,
    env: {
      ...process.env,
      HOST: "127.0.0.1",
      PORT: String(port),
      CLIENT_ORIGIN: "",
      WEB_CLI_AUTH_DIR: authDir,
      ALLOWED_PROJECT_DIRS: projectDir,
      MAX_ACTIVE_SESSIONS: "3",
      MAX_RETAINED_SESSIONS: "50",
      AGENTS_CONFIG_JSON: JSON.stringify([
        {
          id: "codex",
          label: "Codex",
          command: process.execPath,
          args: [path.resolve(root, "server/test/fixtures/terminal-agent.cjs")]
        },
        { id: "shell", label: "Shell", command: "/bin/sh", args: ["-i"] }
      ])
    },
    stdio: ["ignore", "pipe", "pipe"]
  });

  let output = "";
  child.stdout.on("data", (data) => {
    output = (output + data).slice(-6000);
  });
  child.stderr.on("data", (data) => {
    output = (output + data).slice(-6000);
  });

  let browser;

  try {
    let ready = false;
    for (let i = 0; i < 100; i++) {
      try {
        if ((await fetch(base + "/api/health")).ok) {
          ready = true;
          break;
        }
      } catch {}
      if (child.exitCode !== null) throw new Error("Backend failed: " + output);
      await pause(100);
    }
    assert.ok(ready, "Backend ready on ephemeral port " + port);

    // Read initial setup code
    let setupCode = "";
    for (let i = 0; i < 50; i++) {
      const p = path.join(authDir, "setup-code.txt");
      if (fs.existsSync(p)) {
        setupCode = fs.readFileSync(p, "utf8").trim();
        break;
      }
      await pause(100);
    }
    assert.ok(setupCode, "Setup code generated by server");

    browser = await puppeteer.launch({
      executablePath: resolveChromePath() || process.env.CHROME_PATH || "/usr/bin/google-chrome",
      headless: true,
      args: ["--no-sandbox", "--disable-gpu"]
    });

    const page1 = await browser.newPage();
    const pageErrors = [];
    page1.on("pageerror", (err) => pageErrors.push(err.message));

    await page1.setViewport({ width: 1280, height: 800 });
    await page1.goto(base, { waitUntil: "networkidle0" });

    // Step 1: Initial 2FA setup
    await page1.waitForSelector("input[name=username]");
    await page1.type("input[type=password]", setupCode); // setupCode input
    await page1.type("input[name=username]", "testadmin");
    await page1.type("input[name=password]", "super-secure-password-12345");

    const setupResponsePromise = page1.waitForResponse(
      (res) => res.url().includes("/api/auth/setup") && res.request().method() === "POST"
    );
    await page1.click("button.primary");
    const setupJson = await (await setupResponsePromise).json();
    assert.ok(setupJson.secret, "Setup returned TOTP secret");

    await page1.waitForSelector("input[name=code]");
    const totpCode = new TOTP({
      secret: Secret.fromBase32(setupJson.secret),
      algorithm: "SHA1",
      digits: 6,
      period: 30
    }).generate();

    await page1.type("input[name=code]", totpCode);
    await page1.click("button.primary");

    await page1.waitForFunction(() => document.body.textContent.includes("Đã lưu, mở terminal"));
    await page1.$$eval("button", (buttons) => {
      const btn = buttons.find((b) => b.textContent.includes("Đã lưu, mở terminal"));
      btn?.click();
    });

    // Step 2: Create Session A
    await page1.waitForFunction(() => {
      const btns = Array.from(document.querySelectorAll("button"));
      return btns.some((b) => b.textContent.includes("+ Phiên mới") || b.textContent.includes("Tạo phiên đầu tiên"));
    });
    await page1.$$eval("button", (buttons) => {
      const btn = buttons.find(
        (b) => b.textContent.includes("+ Phiên mới") || b.textContent.includes("Tạo phiên đầu tiên")
      );
      btn?.click();
    });

    await page1.waitForSelector(".new-session-dialog[open]");
    await page1.$$eval(".new-session-dialog button[role=tab]", (tabs) => {
      const codexTab = tabs.find((t) => t.textContent.includes("Codex"));
      codexTab?.click();
    });
    await pause(100);
    await page1.$$eval(".new-session-dialog button[type=submit]", (buttons) => {
      buttons[0]?.click();
    });

    await page1.waitForFunction(() => !document.querySelector("#command-input")?.disabled, {
      timeout: 15000
    });
    const sessionAId = await page1.$eval(
      'select[aria-label="Chuyển phiên terminal"]',
      (select) => select.value
    );
    assert.ok(sessionAId, "Session A created with valid UUID");

    // The first authenticated render began while logged out. Once an active session
    // exists, the production hook must schedule its own 5s refresh rather than rely
    // on the explicit load/create requests above.
    await page1.waitForNetworkIdle({ idleTime: 250, timeout: 3000 });
    const isSessionPoll = (response) => {
      const url = new URL(response.url());
      return response.request().method() === "GET" && url.pathname.endsWith("/api/web-cli/api/sessions");
    };
    await page1.waitForResponse(isSessionPoll, { timeout: 7500 });
    await page1.waitForResponse(isSessionPoll, { timeout: 7500 });

    // Test terminal input on session A
    await page1.type("#command-input", "echo HELLO_FROM_A");
    await page1.click(".composer button[type=submit]");
    await page1.waitForFunction(
      () => document.querySelector(".xterm-screen")?.textContent.includes("HELLO_FROM_A"),
      { timeout: 8000 }
    );

    // Step 3 (U01): Create Session B while Session A is running
    await page1.$$eval("button", (buttons) => {
      const btn = buttons.find((b) => b.textContent.includes("+ Phiên mới"));
      btn?.click();
    });

    await page1.waitForSelector(".new-session-dialog[open]");
    await page1.$$eval(".new-session-dialog button[role=tab]", (tabs) => {
      const codexTab = tabs.find((t) => t.textContent.includes("Codex"));
      codexTab?.click();
    });
    await pause(100);
    const createPromise = page1.waitForResponse(
      (res) => res.url().includes("/api/sessions") && res.request().method() === "POST"
    );
    await page1.$$eval(".new-session-dialog button[type=submit]", (buttons) => {
      buttons[0]?.click();
    });
    const createRes = await createPromise;
    const createData = await createRes.json();
    const sessionBId = createData.session.id;
    assert.ok(sessionBId && sessionBId !== sessionAId, "Session B created distinct from Session A");

    // Wait for UI to update active session and terminal to connect
    await page1.waitForFunction(
      (id) => document.querySelector('select[aria-label="Chuyển phiên terminal"]')?.value === id,
      {},
      sessionBId
    );
    await page1.waitForFunction(() => !document.querySelector("#command-input")?.disabled, {
      timeout: 15000
    });

    // Check backend list: both A and B are running
    const sessionsRes = await page1.evaluate(async () => {
      const res = await fetch("/api/web-cli/api/sessions");
      return res.json();
    });
    assert.equal(sessionsRes.sessions.length, 2, "Both sessions exist in backend");
    assert.equal(sessionsRes.capacity.active, 2, "Active capacity count is 2");

    // Step 4 (U02 & U03): Draft isolation and switching A <-> B
    // In session B, type a draft
    await page1.type("#command-input", "DRAFT_IN_B");
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "DRAFT_IN_B",
      "Draft entered in Session B"
    );

    // Switch to session A
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionAId);
    await pause(300);

    // Verify Session A draft is initially empty
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "",
      "Session A draft is isolated and empty"
    );

    // In session A, type a draft
    await page1.type("#command-input", "DRAFT_IN_A");
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "DRAFT_IN_A",
      "Draft entered in Session A"
    );

    // Switch back to session B
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionBId);
    await pause(300);
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "DRAFT_IN_B",
      "Session B draft restored accurately"
    );

    // Switch back to session A
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionAId);
    await pause(300);
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "DRAFT_IN_A",
      "Session A draft restored accurately"
    );

    // Verify storage does not persist prompt drafts
    const storageDump = await page1.evaluate(() => {
      return {
        local: JSON.stringify(window.localStorage),
        session: JSON.stringify(window.sessionStorage)
      };
    });
    assert.ok(
      !storageDump.local.includes("DRAFT_IN_") && !storageDump.session.includes("DRAFT_IN_"),
      "Draft prompts are kept strictly in RAM, not persisted to storage"
    );

    // Rapid switch loop (U02): 10 switches without error
    for (let i = 0; i < 10; i++) {
      const target = i % 2 === 0 ? sessionBId : sessionAId;
      await page1.select('select[aria-label="Chuyển phiên terminal"]', target);
      await pause(50);
    }
    assert.equal(pageErrors.length, 0, "No page errors during rapid session switches");

    // Step 4.5 (Gate U08 & U09): Codex Shift + Left Arrow shortcut
    // Switch to Session B (agent: codex)
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionBId);
    await pause(300);

    // Verify Shift + ← button is visible for codex
    const shiftLeftBtn = await page1.evaluate(() => {
      const btns = Array.from(document.querySelectorAll(".shortcut-row button"));
      const btn = btns.find((b) => b.textContent.includes("Shift + ←"));
      return btn
        ? { text: btn.textContent.trim(), title: btn.getAttribute("title"), disabled: btn.disabled }
        : null;
    });
    assert.ok(shiftLeftBtn, "Shift + Left Arrow button is rendered for Codex session");
    assert.equal(
      shiftLeftBtn.title,
      "Shift + mũi tên trái — trả lời câu hỏi Codex",
      "Shift + Left Arrow has correct Vietnamese tooltip"
    );
    assert.equal(shiftLeftBtn.disabled, false, "Shift + Left Arrow button is enabled when connected");

    // Click Shift + ← on Session B while keeping draft
    await page1.evaluate(() => {
      const btns = Array.from(document.querySelectorAll(".shortcut-row button"));
      const b = btns.find((btn) => btn.textContent.includes("Shift + ←"));
      b?.click();
    });

    // Verify draft in Session B was NOT flushed
    assert.equal(
      await page1.$eval("#command-input", (el) => el.value),
      "DRAFT_IN_B",
      "Draft in Session B is preserved after clicking Shift + Left Arrow (no draft flush)"
    );

    // Verify Session B terminal received the hex sequence 1b5b313b3244
    try {
      await page1.waitForFunction(
        () => document.querySelector(".xterm-screen")?.textContent.includes("1b5b313b3244"),
        { timeout: 8000 }
      );
    } catch (err) {
      const scr = await page1.evaluate(() => document.querySelector(".xterm-screen")?.textContent);
      console.error("DEBUG xterm text on Shift+Left failure:", scr);
      throw err;
    }

    // Switch to Session A and verify Session A terminal did NOT receive Shift + Left Arrow
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionAId);
    await pause(300);
    const sessionAText = await page1.evaluate(
      () => document.querySelector(".xterm-screen")?.textContent || ""
    );
    assert.ok(
      !sessionAText.includes("1b5b313b3244"),
      "Session A did NOT receive the Shift + Left Arrow key sent to Session B"
    );

    // Create Session C with agent: shell
    await page1.$$eval("button", (buttons) => {
      const btn = buttons.find((b) => b.textContent.includes("+ Phiên mới"));
      btn?.click();
    });
    await page1.waitForSelector(".new-session-dialog[open]");
    // Select agent: shell via tab (labeled "Terminal")
    await page1.$$eval(".new-session-dialog button[role=tab]", (tabs) => {
      const shellTab = tabs.find(
        (t) => t.textContent.includes("Terminal") || t.textContent.includes("Shell")
      );
      shellTab?.click();
    });
    await pause(100);
    const createCPromise = page1.waitForResponse(
      (res) => res.url().includes("/api/sessions") && res.request().method() === "POST"
    );
    await page1.$$eval(".new-session-dialog button[type=submit]", (buttons) => {
      buttons[0]?.click();
    });
    const createCRes = await createCPromise;
    const createCData = await createCRes.json();
    const sessionCId = createCData.session.id;
    assert.ok(sessionCId && sessionCId !== sessionAId && sessionCId !== sessionBId);

    await page1.waitForFunction(
      (id) => document.querySelector('select[aria-label="Chuyển phiên terminal"]')?.value === id,
      {},
      sessionCId
    );
    await page1.waitForFunction(() => !document.querySelector("#command-input")?.disabled, {
      timeout: 15000
    });

    // Verify Session C (agent: shell) does NOT render Shift + ←
    const shellHasShiftLeft = await page1.evaluate(() => {
      const btns = Array.from(document.querySelectorAll(".shortcut-row button"));
      return btns.some((b) => b.textContent.includes("Shift + ←"));
    });
    assert.ok(!shellHasShiftLeft, "Shell session does NOT display Shift + Left Arrow button (Gate U09)");

    // Switch back to Session A for tab 2 test
    await page1.select('select[aria-label="Chuyển phiên terminal"]', sessionAId);
    await pause(300);

    // Step 5 (U10 & U11): Second tab as viewer and control transfer
    const page2 = await browser.newPage();
    const page2Errors = [];
    page2.on("pageerror", (err) => page2Errors.push(err.message));
    await page2.setViewport({ width: 1280, height: 800 });

    // Open same session in Tab 2
    await page2.goto(`${base}/#session=${sessionAId}`, { waitUntil: "networkidle0" });
    await pause(1000);

    // Check Tab 2 shows viewer banner
    const isViewer = await page2.evaluate(() => {
      return Boolean(document.querySelector(".viewer-banner"));
    });
    assert.ok(isViewer, "Tab 2 displays viewer status banner when attaching to session already controlled by Tab 1");

    // Tab 2 input is disabled/blocked
    const tab2InputBlocked = await page2.evaluate(() => {
      return document.querySelector("#command-input")?.disabled;
    });
    assert.ok(tab2InputBlocked, "Tab 2 command composer is disabled in viewer mode");

    // Check Tab 2 has Shift + ← disabled (Gate U09)
    const tab2ShiftDisabled = await page2.evaluate(() => {
      const btns = Array.from(document.querySelectorAll(".shortcut-row button"));
      const btn = btns.find((b) => b.textContent.includes("Shift + ←"));
      return btn?.disabled;
    });
    assert.equal(tab2ShiftDisabled, true, "Shift + Left Arrow button is disabled for viewer tab");

    // Close Tab 1 to trigger promotion of Tab 2 to controller
    await page1.close();
    await pause(1000);

    // Tab 2 should now be promoted to controller
    await page2.waitForFunction(() => !document.querySelector(".viewer-banner"), {
      timeout: 5000
    });
    const tab2CanInput = await page2.evaluate(() => {
      return !document.querySelector("#command-input")?.disabled;
    });
    assert.ok(tab2CanInput, "Tab 2 promoted to controller and input unblocked after Tab 1 disconnects");

    // Step 6 (U12): Page reload restores active session from sessionStorage
    await page2.reload({ waitUntil: "networkidle0" });
    await page2.waitForFunction(() => !document.querySelector("#command-input")?.disabled, {
      timeout: 10000
    });
    const reloadedSessionId = await page2.$eval(
      'select[aria-label="Chuyển phiên terminal"]',
      (select) => select.value
    );
    assert.equal(reloadedSessionId, sessionAId, "Reload accurately restored active session from sessionStorage");

    await page2.close();

    console.log(
      JSON.stringify(
        {
          passed: true,
          checks: [
            "U01: Independent creation of Session B while A running",
            "U02: Multiple session switching without crosstalk",
            "U03: Pure RAM draft isolation per session",
            "U08 & U09: Codex Shift + Left Arrow sends \\x1b[1;2D without flushing draft, hidden for shell and disabled for viewer",
            "U10 & U11: Multiple tabs controller vs viewer locking and promotion",
            "U12: Accurate session restore upon reload"
          ]
        },
        null,
        2
      )
    );
  } finally {
    if (browser) await browser.close();
    child.kill("SIGTERM");
    await pause(300);
    if (child.exitCode === null) child.kill("SIGKILL");
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error("SMOKE TEST FAILED:", err);
  process.exit(1);
});
